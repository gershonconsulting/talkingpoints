// Copies schema.sql + seed.sql into functions/_schema.js so the app applies them itself on first
// request (no wrangler, no API token). Runs as the Cloudflare Pages build command; the output is
// also committed so it works without a build step.
import { readFileSync, writeFileSync } from 'node:fs';
const sql = ['schema.sql', 'seed.sql'].map((f) => readFileSync(new URL(`../${f}`, import.meta.url), 'utf8')).join('\n')
  .split('\n').filter((l) => !l.trim().startsWith('--')).join('\n');
if (/[`$\\]/.test(sql)) throw new Error('schema/seed may not contain ` $ or \\');
writeFileSync(new URL('../functions/_schema.js', import.meta.url),
  `// GENERATED by scripts/gen-schema.mjs from schema.sql + seed.sql — do not edit by hand.\nexport const SQL = \`\n${sql}\`;\n`);
console.log('functions/_schema.js written');
